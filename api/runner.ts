// ============================================================================
// Inline ConstraintMemory (simplified, in-memory only)
// ============================================================================

interface Constraint {
    id: string;
    type: 'forbid' | 'require' | 'prefer';
    rule: string;
    scope: string;
    priority: number;
    source: string;
    createdAt: number;
}

class ConstraintMemory {
    private constraints: Constraint[] = [];

    store(
        type: 'forbid' | 'require' | 'prefer',
        rule: string,
        scope: string,
        options: { priority?: number; source?: string } = {}
    ): Constraint {
        const constraint: Constraint = {
            id: crypto.randomUUID(),
            type,
            rule,
            scope,
            priority: options.priority ?? 5,
            source: options.source ?? 'system',
            createdAt: Date.now(),
        };
        this.constraints.push(constraint);
        return constraint;
    }

    recall(scope: string): Constraint[] {
        return this.constraints.filter(c => c.scope === scope || c.scope === '*');
    }

    formatForContext(scope: string): string {
        const constraints = this.recall(scope);
        if (constraints.length === 0) return 'No constraints for this scope.';
        return constraints
            .map(c => `[${c.type.toUpperCase()}] ${c.rule}`)
            .join('\n');
    }
}

// ============================================================================
// Inline IntentClassifier (simplified)
// ============================================================================

type Intent = 'workflow' | 'question' | 'command' | 'clarification' | 'unknown';

interface ClassificationResult {
    intent: Intent;
    confidence: number;
    latencyMs: number;
}

class IntentClassifier {
    classify(input: { input: string }): { ok: true; value: ClassificationResult } | { ok: false; error: Error } {
        const startTime = performance.now();
        const text = input.input.toLowerCase();

        let intent: Intent = 'unknown';
        let confidence = 0.5;

        // Simple keyword-based classification
        if (text.includes('refactor') || text.includes('implement') || text.includes('create') || text.includes('build')) {
            intent = 'workflow';
            confidence = 1.0;
        } else if (text.includes('?') || text.includes('what') || text.includes('how') || text.includes('why')) {
            intent = 'question';
            confidence = 0.9;
        } else if (text.includes('run') || text.includes('execute') || text.includes('do')) {
            intent = 'command';
            confidence = 0.85;
        }

        return {
            ok: true,
            value: {
                intent,
                confidence,
                latencyMs: performance.now() - startTime,
            },
        };
    }
}

