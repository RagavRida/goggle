export async function runGoldenDemo(log: LogCallback) {
    log('\n');
    log('THE AMNESIAC REFACTOR - ContextOS Golden Run Demo');
    log('------------------------------------------------');
    log('Powered by Antigravity Agent (Vercel Serverless)');
    log('\n');

    // Initialize components
    const memory = new ConstraintMemory();
    const classifier = new IntentClassifier();
    const reasoning = new GeminiReasoning();
    const testRunner = new MockTestRunner();

    const startTime = Date.now();

    // TURN 1: Constraint Injection
    log('👤 USER TURN 1: Constraint Injection');
    log('💬 "Hey, remember: never use arrow functions in the legacy module, only standard functions."');
    log('\n');

    await delay(300);

    // Memory gating
    const entropy = 1.0;
    log(`   🚪[GATING] Entropy: ${entropy.toFixed(2)} → Gate OPEN`);

    // Store constraint
    memory.store(
        'forbid',
        'Never use arrow functions in legacy modules - use standard function declarations only',
        'auth',
        { priority: 10, source: 'user' }
    );

    log('\n   ✅ SYSTEM: Stored constraint in memory.\n');
    await delay(500);

    // TURN 2: The Task
    log('👤 USER TURN 2: The Refactor Task');
    log('💬 "Refactor auth.ts to use Async/Await. Run tests when done."');
    log('\n');

    await delay(300);

    // Step 1: Intent Classification
    log('┌─ STEP 1: Intent Classification ─────────────────────────────────────┐');
    const taskInput = 'Refactor auth.ts to use Async/Await. Run tests when done.';
    const classification = classifier.classify({ input: taskInput });

    if (classification.ok) {
        const { intent, confidence } = classification.value;
        log(`│  Intent: ${intent.toUpperCase()}`);
        log(`│  Confidence: ${(confidence * 100).toFixed(0)}% `);
        log(`│  → Routing to Dev Teammate Agent`);
    }
    log('└──────────────────────────────────────────────────────────────────────┘\n');

    await delay(300);

    // Step 2: Context Retrieval
    log('┌─ STEP 2: Context Retrieval ──────────────────────────────────────────┐');
    const constraints = memory.recall('auth');
    log(`│  Scope: auth`);
    log(`│  Recalled: ${constraints.length} constraint(s)`);

    for (const c of constraints) {
        log(`│  📌[${c.type}] "${c.rule}"`);
    }
    log('└──────────────────────────────────────────────────────────────────────┘\n');

    await delay(300);

    // Step 3: Read Legacy File
    log('┌─ STEP 3: Reading Legacy File ────────────────────────────────────────┐');
    log('│  File: legacy-auth.js');
    log('│  Preview:');
    const lines = MOCK_LEGACY_CODE.split('\n').filter(l => l.trim().length > 0).slice(0, 5);
    for (const line of lines) {
        log(`│    ${line} `);
    }
    log('│    ...');
    log('└──────────────────────────────────────────────────────────────────────┘\n');

    // Self-Correcting Loop
    const maxAttempts = 3;
    const constraintContext = memory.formatForContext('auth');

    for (let attempt = 1; attempt <= maxAttempts; attempt++) {
        log(`\n  🔄 ATTEMPT ${attempt}/${maxAttempts}`);
        log('------------------------------------------------');

        // Step 4: Reasoning
        log('\n┌─ STEP 4: Reasoning (Antigravity Agent) ─────────────────────────────┐');
        log('│  🧠 Thinking...');

        const plan = await reasoning.plan(taskInput, constraintContext);

        log(`│  Summary: ${plan.summary}`);
        log(`│  Uses Arrow Functions: ${plan.usesArrowFunctions ? '❌ YES' : '✅ NO'}`);
        log('└──────────────────────────────────────────────────────────────────────┘');

        // Check constraint violation
        if (plan.usesArrowFunctions) {
            log('\n   ⚠️  CONSTRAINT VIOLATION DETECTED!');
            log('   📌 Rule: "Never use arrow functions in legacy modules"');
            log('   → Self-correcting: Regenerating with constraints...\n');
            await delay(300);
            continue;
        }

        // Step 5: Execution
        log('\n┌─ STEP 5: Executing Changes ─────────────────────────────────────────┐');
        log('│  📝 Writing refactored code...');
        log('│  File: src/auth.ts');
        log('│  Lines: ' + plan.code.split('\n').length);
        log('└──────────────────────────────────────────────────────────────────────┘');

        // Step 6: Testing
        log('\n┌─ STEP 6: Running Tests ─────────────────────────────────────────────┐');
        const testResult = await testRunner.run(plan.code);
        const outputLines = testResult.output.split('\n');
        for (const line of outputLines) {
            log(`│  ${line}`);
        }
        log('└──────────────────────────────────────────────────────────────────────┘');

        if (testResult.passed) {
            const duration = ((Date.now() - startTime) / 1000).toFixed(1);
            log('\n✅ SUCCESS!');
            log(`\n   ⏱️  Completed in ${duration}s (${attempt} attempt(s))`);
            log('\n   📝 Would create PR: "Refactor auth.ts to async/await"\n');
            return;
        }

        // Self-correct on test failure
        log('\n   ❌ Tests failed. Analyzing errors...');
        for (const error of testResult.errors) {
            log(`      ${error}`);
        }
        log('   → Self-correcting: Adjusting code...\n');
        await delay(300);
    }

    log('\n❌ FAILED: Max attempts exceeded\n');
}
